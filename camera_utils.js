/* Browser-only helpers. No network calls or persistent storage. */
(function (root) {
  'use strict';
  const POSES = {
    frontal: { label: 'Frontal', hint: 'Schau direkt in die Linse. Halte den Kopf gerade und das Kinn entspannt.' },
    links: { label: 'Leicht nach links', hint: 'Drehe die Nase etwa 20–30° zu deiner linken Schulter. Die Kamera bleibt auf Augenhöhe; beide Augen sollen sichtbar bleiben.' },
    rechts: { label: 'Leicht nach rechts', hint: 'Drehe die Nase etwa 20–30° zu deiner rechten Schulter. Die Kamera bleibt auf Augenhöhe; beide Augen sollen sichtbar bleiben.' }
  };
  function crc32(bytes) {
    let c = 0xffffffff;
    for (const b of bytes) { c ^= b; for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1)); }
    return (c ^ 0xffffffff) >>> 0;
  }
  function concat(parts) {
    const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
    let offset = 0; for (const p of parts) { out.set(p, offset); offset += p.length; } return out;
  }
  function header(size) { const bytes = new Uint8Array(size); return { bytes, view: new DataView(bytes.buffer) }; }
  function makeZip(files) {
    // ZIP STORE; filenames are generated by this app. No library or remote service.
    const local = [], central = []; let offset = 0, centralSize = 0;
    for (const file of files) {
      const name = new TextEncoder().encode(file.name), data = file.data;
      if (!/^[a-zA-Z0-9_.-]+$/.test(file.name)) throw new Error('Ungültiger Dateiname');
      const crc = crc32(data), h = header(30), d = h.view;
      d.setUint32(0, 0x04034b50, true); d.setUint16(4, 20, true);
      d.setUint16(12, 33, true); d.setUint32(14, crc, true);
      d.setUint32(18, data.length, true); d.setUint32(22, data.length, true); d.setUint16(26, name.length, true);
      local.push(h.bytes, name, data);
      const c = header(46), v = c.view;
      v.setUint32(0, 0x02014b50, true); v.setUint16(4, 20, true); v.setUint16(6, 20, true);
      v.setUint16(14, 33, true); v.setUint32(16, crc, true); v.setUint32(20, data.length, true);
      v.setUint32(24, data.length, true); v.setUint16(28, name.length, true); v.setUint32(42, offset, true);
      central.push(c.bytes, name); centralSize += 46 + name.length; offset += 30 + name.length + data.length;
    }
    const end = header(22), e = end.view;
    e.setUint32(0, 0x06054b50, true); e.setUint16(8, files.length, true); e.setUint16(10, files.length, true);
    e.setUint32(12, centralSize, true); e.setUint32(16, offset, true);
    return concat([...local, ...central, end.bytes]);
  }
  function fitSize(width, height, max = 2560) {
    if (!(width > 0 && height > 0)) throw new Error('Kamera noch nicht bereit');
    const scale = Math.min(1, max / Math.max(width, height));
    return { width: Math.max(1, Math.round(width * scale)), height: Math.max(1, Math.round(height * scale)) };
  }
  function photoName(pose, number) {
    if (!POSES[pose] || !Number.isInteger(number) || number < 1) throw new Error('Ungültige Aufnahme');
    return `portrait-${pose}-${String(number).padStart(2, '0')}.jpg`;
  }
  const api = { POSES, crc32, makeZip, fitSize, photoName };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.PortraitCapture = api;
})(typeof window === 'undefined' ? globalThis : window);
